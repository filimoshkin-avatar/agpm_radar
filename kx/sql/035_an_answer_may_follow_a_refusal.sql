BEGIN;

SET search_path = kx, public;

-- ---------------------------------------------------------------------------
-- Отказ перестаёт навсегда занимать ключ кэша
--
-- 017 завела один уникальный индекс на тройку ADR-0006 §10 — вопрос, область,
-- релиз, — и триггер `research_answers_immutable`, запрещающий и UPDATE, и
-- DELETE. Вместе это значит больше, чем задумывалось: **раз записанный отказ
-- занимает ключ навсегда**. Полученный позже настоящий ответ на тот же вопрос
-- возвращается читателю и не сохраняется — `ON CONFLICT ... DO NOTHING`. Вопрос
-- становится некэшируемым: каждый следующий читатель оплачивает свежий вызов
-- модели, и каждый такой вызов может снова выпасть в отказ.
--
-- Измерено на проде 26.08.2026: «Расскажи про «Человеко-агентная система»»
-- ответил в одном прогоне за 17,8 с и отказал в следующем, при том же промпте и
-- тех же цитатах; в базе по нему одна строка — отказ от 25.08 13:37. Ключей,
-- занятых отказом, было 40, из них 4 на действующих запросах приветственного
-- пула.
--
-- Правило «записанный ответ не переписывается» задумано про **ответы**.
-- Отказ — это «не смогли сейчас», а не решение, которое стоит замораживать.
--
-- Поэтому ключ делится надвое, а не ослабляется. `an_answer_or_a_refusal` уже
-- гарантирует, что строка — либо ответ, либо отказ, никогда не оба; два
-- частичных индекса на той же тройке дают ровно один ответ и ровно один отказ
-- на ключ. Ничего не удаляется и не переписывается: триггер остаётся как был,
-- отказы остаются для анализа, рост ограничен двумя строками на вопрос.
--
-- Существующие строки под это подходят без правки: старый индекс уже не давал
-- больше одной строки на ключ, значит и ответ там не более одного, и отказ не
-- более одного.
-- ---------------------------------------------------------------------------

DROP INDEX research_answers_cache_key;

-- ADR-0006 §10 для ответа: он по-прежнему один на вопрос, область и релиз.
CREATE UNIQUE INDEX research_answers_answer_key
    ON research_answers (normalized_question, scope, coalesce(release_id, ''))
    WHERE answer_text IS NOT NULL;

-- И один отказ на тот же ключ — чтобы отказы не копились по одному на вопрос,
-- но и не мешали ответу появиться.
CREATE UNIQUE INDEX research_answers_refusal_key
    ON research_answers (normalized_question, scope, coalesce(release_id, ''))
    WHERE refusal_reason IS NOT NULL;

UPDATE metadata SET value = '35'::jsonb, updated_at = clock_timestamp()
WHERE key = 'schema_version';

COMMIT;
